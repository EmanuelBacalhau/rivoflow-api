import { NodeEntity } from '@application/entities/node.entity';
import { ExternalServiceError } from '@application/errors/application/external-service.error';
import { GoogleGenAI } from '@google/genai';
import { Injectable } from 'src/kernel/decorators/injectable';
import { AppConfig } from 'src/shared/config/app.config';
import { FileStorageGateway } from '../aws/file-storage.gateway';
import { GeminiPricing } from 'src/shared/config/gemini-pricing';

@Injectable()
export class ImageGatewayAI {
  private readonly ai: GoogleGenAI;

  constructor(
    private readonly fileStorageGateway: FileStorageGateway,
    private readonly appConfig: AppConfig,
  ) {
    this.ai = new GoogleGenAI({
      apiKey: this.appConfig.ai.nanobananaApiKey,
    });
  }

  async processImage(
    params: ImageGatewayAI.ProcessImageInput,
  ): Promise<ImageGatewayAI.ProcessImageOutput> {
    const imagesBase64 = await Promise.all(
      params.images.map(async ({ key, filename }) => ({
        base64: await this.transformS3KeyToBase64(key),
        mimeType: `image/${filename.split('.').pop()}`,
      })),
    );

    const contents: ImageGatewayAI.ContentType[] = imagesBase64.map(({ base64, mimeType }) => {
      return {
        inlineData: {
          data: base64,
          mimeType,
        },
      };
    });

    contents.push({
      text: params.prompt,
    });

    let result: Awaited<ReturnType<typeof this.ai.models.generateContent>>;

    try {
      result = await this.ai.models.generateContent({
        model: 'gemini-3-pro-image-preview',
        contents: contents,
        config: {
          responseModalities: [
            'IMAGE',
          ],
          imageConfig: {
            aspectRatio: params.parameters.aspectRatio,
            imageSize: params.parameters.quality,
          },
        },
      });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown AI error';
      throw new ExternalServiceError(`AI image generation failed: ${message}`);
    }

    if (!result.candidates || result.candidates.length === 0) {
      throw new ExternalServiceError('No candidates returned from AI');
    }

    let key = '';
    for (const part of result.candidates[0].content?.parts || []) {
      if (part.inlineData?.data && part.inlineData?.mimeType) {
        const buffer = Buffer.from(part.inlineData.data, 'base64');

        key = await this.fileStorageGateway.uploadFile({
          buffer,
          extension: 'png',
          contentType: 'image/png',
        });
      }
    }

    const totalTokens = GeminiPricing.outputImageTokens[params.parameters.quality];

    if (!key) {
      throw new ExternalServiceError('No image was generated by AI');
    }

    return {
      key,
      totalTokens,
    };
  }

  private async transformS3KeyToBase64(key: string): Promise<string> {
    const file = await this.fileStorageGateway.getFile(key);
    const base64 = Buffer.from(file).toString('base64');
    return base64;
  }
}

export namespace ImageGatewayAI {
  export type ProcessImageInput = {
    images: {
      key: string;
      filename: string;
    }[];
    prompt: string;
    parameters: NodeEntity.NodeDataGeneration['parameters'];
  };

  export type ProcessImageOutput = {
    key: string;
    totalTokens: number;
  };

  export type ImageType = {
    inlineData: {
      data: string;
      mimeType: string;
    };
  };

  export type TextType = {
    text: string;
  };

  export type ContentType = ImageType | TextType;
}
