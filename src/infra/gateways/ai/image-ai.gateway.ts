import { AspectRatioEnum, QualityEnum } from '@application/entities/node-enums';
import { ApplicationError } from '@application/errors/application/application-error';
import { ErrorCode } from '@application/errors/error-code';
import { GoogleGenAI } from '@google/genai';
import { Injectable } from 'src/kernel/decorators/injectable';
import { AppConfig } from 'src/shared/config/app.config';
import { GeminiPricing } from 'src/shared/config/gemini-pricing';
import { GeminiUsageMetadata } from 'src/shared/utils/credit-calculator';
import { FileStorageGateway } from '../aws/file-storage.gateway';

@Injectable()
export class ImageGatewayAI {
  private readonly ai: GoogleGenAI;

  constructor(
    private readonly fileStorageGateway: FileStorageGateway,
    private readonly appConfig: AppConfig,
  ) {
    this.ai = new GoogleGenAI({
      apiKey: this.appConfig.ai.nanobananaApiKey,
    });
  }

  async processImage(
    params: ImageGatewayAI.ProcessImageInput,
  ): Promise<ImageGatewayAI.ProcessImageOutput> {
    const contents = await this.prepareContents(params);

    let result: Awaited<ReturnType<typeof this.ai.models.generateContent>>;

    try {
      result = await this.ai.models.generateContent({
        model: ImageGatewayAI.Model,
        contents: contents,
        config: {
          responseModalities: [
            'IMAGE',
          ],
          imageConfig: {
            aspectRatio: params.parameters.aspectRatio,
            imageSize: params.parameters.quality,
          },
        },
      });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown AI error';
      throw new ApplicationError(ErrorCode.EXTERNAL_SERVICE_ERROR,`AI image generation failed: ${message}`);
    }

    if (!result.candidates || result.candidates.length === 0) {
      throw new ApplicationError(ErrorCode.EXTERNAL_SERVICE_ERROR,'No candidates returned from AI');
    }

    let key = '';
    for (const part of result.candidates[0].content?.parts || []) {
      if (part.inlineData?.data && part.inlineData?.mimeType) {
        const buffer = Buffer.from(part.inlineData.data, 'base64');

        key = await this.fileStorageGateway.uploadFile({
          buffer,
          extension: 'png',
          contentType: 'image/png',
          accountId: params.accountId,
          flowId: params.flowId,
        });
      }
    }

    if (!key) {
      throw new ApplicationError(ErrorCode.EXTERNAL_SERVICE_ERROR,'No image was generated by AI');
    }

    const rawUsage = result.usageMetadata || {};

    const usage = {
      promptTokenCount: rawUsage.promptTokenCount ?? 0,
      candidatesTokenCount: rawUsage.candidatesTokenCount ?? 0,
      totalTokenCount: rawUsage.totalTokenCount ?? 0,
      thoughtsTokenCount:
        rawUsage.promptTokensDetails?.find((d) => d.modality === 'TEXT')?.tokenCount ?? undefined,
      promptTokensDetails: rawUsage.promptTokensDetails as any,
      candidatesTokensDetails: rawUsage.candidatesTokensDetails as any,
    };

    const quality = params.parameters.quality;
    const totalTokens = GeminiPricing.outputImageTokens[quality];

    return {
      key,
      totalTokens,
      usage,
    };
  }
  private async prepareContents(
    params: ImageGatewayAI.ProcessImageInput,
  ): Promise<ImageGatewayAI.ContentType[]> {
    const imagesBase64 = await Promise.all(
      params.images.map(async ({ key }) => ({
        base64: await this.fileStorageGateway.transformS3KeyToBase64(key),
        mimeType: `image/${key.split('.').pop()}`,
      })),
    );

    const contents: ImageGatewayAI.ContentType[] = imagesBase64.map(({ base64, mimeType }) => {
      return {
        inlineData: {
          data: base64,
          mimeType,
        },
      };
    });

    contents.push({
      text: params.prompt,
    });

    return contents;
  }
}

export namespace ImageGatewayAI {
  export type ProcessImageInput = {
    images: {
      key: string;
    }[];
    prompt: string;
    parameters: { aspectRatio: AspectRatioEnum; quality: QualityEnum };
    accountId: string;
    flowId: string;
  };

  export type ProcessImageOutput = {
    key: string;
    totalTokens: number;
    usage: GeminiUsageMetadata;
  };

  export type ImageType = {
    inlineData: {
      data: string;
      mimeType: string;
    };
  };

  export type TextType = {
    text: string;
  };

  export type ContentType = ImageType | TextType;

  export const Model = 'gemini-3.1-flash-image-preview';
}
